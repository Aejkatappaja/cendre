local M = {}

-- Terminals and multiplexers. Each one takes the same sixteen ANSI slots the
-- palette already derives, so none of these files decides a colour: they only
-- decide a syntax.

local palette = require("cendre.palette")

local HEADER = "# cendre · %s · https://github.com/Aejkatappaja/cendre"
local GENERATED = "# generated by scripts/extras.lua, do not edit"

--- The sixteen ANSI slots in order, so every terminal writer indexes the same list.
--- @param c table resolved palette
--- @return string[]
local function ansi(c)
  return {
    c.terminal_black, c.terminal_red, c.terminal_green, c.terminal_yellow,
    c.terminal_blue, c.terminal_magenta, c.terminal_cyan, c.terminal_white,
    c.terminal_bright_black, c.terminal_bright_red, c.terminal_bright_green,
    c.terminal_bright_yellow, c.terminal_bright_blue, c.terminal_bright_magenta,
    c.terminal_bright_cyan, c.terminal_bright_white,
  }
end

--- @param bg string depth name
--- @return string
function M.ghostty(bg)
  local c = palette.get(bg)
  local out = {
    HEADER:format(bg), GENERATED, "",
    "background = " .. c.bg0,
    "foreground = " .. c.fg,
    "cursor-color = " .. c.ember,
    "cursor-text = " .. c.bg0,
    "selection-background = " .. c.vis,
    "selection-foreground = " .. c.fg,
    "",
  }
  for i, hex in ipairs(ansi(c)) do
    table.insert(out, ("palette = %d=%s"):format(i - 1, hex))
  end
  return table.concat(out, "\n") .. "\n"
end

