    "selection_background " .. c.vis,
    "selection_foreground " .. c.fg,
    "url_color " .. c.frost,
    "active_border_color " .. c.ember,
    "inactive_border_color " .. c.bg3,
    "bell_border_color " .. c.warn,
    "active_tab_background " .. c.bg0,
    "active_tab_foreground " .. c.fg,
    "inactive_tab_background " .. c.bg_deep,
    "inactive_tab_foreground " .. c.comment,
    "",
  }
  for i, hex in ipairs(slots) do
    if i == 1 then table.insert(out, "# normal") end
    if i == 9 then table.insert(out, "\n# bright") end
    table.insert(out, ("color%d %s"):format(i - 1, hex))
  end
  return table.concat(out, "\n") .. "\n"
end

