--- foot takes bare hex without the leading hash.
--- @param bg string
--- @return string
--- Konsole reads KConfig INI and wants decimal triplets. No header comment: every
--- scheme KDE ships is bare, and this is the one file here nobody could test.
---
--- The Faint set repeats the normal colours. The palette has no dimmed pigment to
--- put there, deriving one would be five colours chosen in a theme whose whole
--- claim is that none are, and leaving the sections out lets Konsole fall back to
--- its own defaults, which are off-palette.
--- @param bg string
--- @return string
function M.konsole(bg)
  local c = palette.get(bg)
  local s = ansi(c)

  local function triplet(hex)
    local r, g, b = hex:match("^#(%x%x)(%x%x)(%x%x)$")
    return ("%d,%d,%d"):format(tonumber(r, 16), tonumber(g, 16), tonumber(b, 16))
  end

  local out = {}
  local function section(name, hex)
    vim.list_extend(out, { "[" .. name .. "]", "Color=" .. triplet(hex), "" })
  end

  section("Background", c.bg0)
  section("BackgroundFaint", c.bg_deep)
  section("BackgroundIntense", c.bg1)

  for i = 1, 8 do
    local slot = "Color" .. (i - 1)
    section(slot, s[i])
    section(slot .. "Faint", s[i])
    section(slot .. "Intense", s[i + 8])
  end

  section("Foreground", c.fg)
  section("ForegroundFaint", c.fg_dim)
  section("ForegroundIntense", c.fg)

  vim.list_extend(out, {
    "[General]",
    "Description=" .. palette.name(bg),
    "Opacity=1",
    "Wallpaper=",
  })

  return table.concat(out, "\n") .. "\n"
end

function M.foot(bg)
  local c = palette.get(bg)
  local s = ansi(c)
  local bare = function(hex) return hex:sub(2) end
  local out = {
    HEADER:format(bg), GENERATED,
    "# then in foot.ini:  include=~/.config/foot/cendre.ini", "",
    "[colors]",
    ("cursor=%s %s"):format(bare(c.bg0), bare(c.ember)),
    "foreground=" .. bare(c.fg),
    "background=" .. bare(c.bg0),
    "",
  }
  for i = 1, 8 do
    table.insert(out, ("regular%d=%s"):format(i - 1, bare(s[i])))
  end
  table.insert(out, "")
  for i = 9, 16 do
    table.insert(out, ("bright%d=%s"):format(i - 9, bare(s[i])))
  end
  vim.list_extend(out, {
    "",
    "selection-foreground=" .. bare(c.fg),
    "selection-background=" .. bare(c.vis),
    "",
    ("search-box-no-match=%s %s"):format(bare(c.bg0), bare(c.error)),
    ("search-box-match=%s %s"):format(bare(c.fg), bare(c.bg3)),
    "",
    ("jump-labels=%s %s"):format(bare(c.bg0), bare(c.brass)),
    "urls=" .. bare(c.frost),
  })
  return table.concat(out, "\n") .. "\n"
end

--- iTerm2 and macOS Terminal both read this one. Components are 0 to 1 floats.
--- @param bg string
--- @return string
function M.itermcolors(bg)
  local c = palette.get(bg)
  local s = ansi(c)

  --- @param hex string
  --- @param key string
  --- @return string
  local function colour(hex, key)
    local r, g, b = hex:match("^#(%x%x)(%x%x)(%x%x)$")
    return ([[
	<key>%s</key>
	<dict>
		<key>Red Component</key><real>%.6f</real>
		<key>Green Component</key><real>%.6f</real>
		<key>Blue Component</key><real>%.6f</real>
	</dict>]]):format(key,
      tonumber(r, 16) / 255, tonumber(g, 16) / 255, tonumber(b, 16) / 255)
  end

  local body = {}
  for i, hex in ipairs(s) do
    table.insert(body, colour(hex, ("Ansi %d Color"):format(i - 1)))
  end
  vim.list_extend(body, {
    colour(c.bg0, "Background Color"),
    colour(c.fg, "Foreground Color"),
    colour(c.ember, "Cursor Color"),
    colour(c.bg0, "Cursor Text Color"),
    colour(c.vis, "Selection Color"),
    colour(c.fg, "Selected Text Color"),
    colour(c.frost, "Link Color"),
    colour(c.bg_deep, "Badge Color"),
  })

  return ([[
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
%s
</dict>
</plist>
]]):format(table.concat(body, "\n"))
end

--- @param bg string
--- @return string
--- A theme block for the tokyo-night-tmux plugin, which reads its colours from a
--- case statement in its own src/themes.sh rather than from a file it can be
--- pointed at. So this is a snippet to paste there, not something tmux sources.
--- @param bg string
--- @return string
function M.tokyo_night_tmux(bg)
  local c = palette.get(bg)
  local name = palette.name(bg)

  -- The keys carry ANSI names, but the plugin never renders program output through
  -- this table: every read paints statusbar chrome. So four of them are filled by
  -- the role the plugin actually uses them for, not by the name they carry.
  local slots = {
    -- the bar's own ground, so bg2, not the editor's bg0. A statusbar sits one
    -- layer above the buffer it describes, and this theme has a step for that.
    { "background", c.bg2 },

    { "foreground", c.fg },

    -- read as a foreground, for the count of untracked files. An ANSI black there
    -- lands near 1:1 on the bar ground, which is not dim, it is gone.
    { "black", c.gutter },

    -- the plugin's accent: session block, active pane border, message bar. Ember is
    -- the accent this theme declares, and it is the only warm answer a fire has.
    { "blue", c.ember },

    { "cyan", c.terminal_cyan }, { "green", c.terminal_green },
    { "magenta", c.terminal_magenta }, { "red", c.terminal_red },

    -- foreground of the command bar, over "black" above
    { "white", c.fg },

    { "yellow", c.terminal_yellow },

    -- read as a background, under the active window block and the clock, so it has
    -- to lift off "background" above by enough to mark a state: bg4 is 0.105 of
    -- lightness clear of bg2, where bg3 would have been 0.046 and would whisper.
    -- The plugin also reads this slot as the ink of its session block, over the
    -- accent, where a fill this light only reaches 4.4:1. One value cannot serve
    -- both; the state marker is the one that carries meaning.
    { "bblack", c.bg4 },

    { "bblue", c.terminal_bright_blue },
    { "bcyan", c.terminal_bright_cyan }, { "bgreen", c.terminal_bright_green },
    { "bmagenta", c.terminal_bright_magenta }, { "bred", c.terminal_bright_red },

    -- the dim ink, since "white" above took the bright one
    { "bwhite", c.fg_dim },

    { "byellow", c.terminal_bright_yellow },
  }

  local rows = {}
  for i, slot in ipairs(slots) do
    -- the plugin's own file groups the eight normal slots then the eight bright
    if i == 11 then rows[#rows + 1] = "" end
    rows[#rows + 1] = ('    ["%s"]="%s"'):format(slot[1], slot[2])
  end

  return ([[
%s
%s
#
# The plugin reads its colours from a case statement in its own src/themes.sh, so
# paste this block there, before its default case, then in tmux.conf:
#   set -g @tokyo-night-tmux_theme "%s"
#   set -g @tokyo-night-tmux_transparent 0
#
# The transparent option is not cosmetic here: at 1 the plugin overwrites
# "background" below with tmux's "default", and the bar drops onto the terminal's
# own colour instead of the ground this theme picked for it.
#
# The keys are named after ANSI slots, but the plugin only ever paints its own
# statusbar with them, never program output. Four are filled by role instead of by
# name: "blue" is the accent, "bblack" is a block background, "black" is read as a
# foreground, and "white" is the bright ink. Aligning them to their ANSI names
# would look tidier here and worse on screen.
#
# One thing this block cannot fix: the plugin paints the inactive pane border with
# "bblack" too, the slot that fills the active window block. If that border reads
# too loud, put this in tmux.conf after the plugin runs:
#   set -g pane-border-style "fg=%s"

"%s")
  declare -A THEME=(
%s
  )
  ;;
]]):format(HEADER:format(bg), GENERATED, name, c.bg3, name, table.concat(rows, "\n"))
end

