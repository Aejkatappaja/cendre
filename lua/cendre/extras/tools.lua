--- bat reads a Sublime Text tmTheme, which is an XML property list. Scopes are
--- grouped the way the Neovim treesitter map groups them.
--- @param bg string
--- @return string
function M.bat(bg)
  local c = palette.get(bg)

  --- @param name string
  --- @param scope string|nil
  --- @param fg string|nil
  --- @param bgc string|nil
  --- @param style string|nil
  --- @return string
  local function rule(name, scope, fg, bgc, style)
    local settings = {}
    if fg then table.insert(settings, ("\t\t\t\t<key>foreground</key>\n\t\t\t\t<string>%s</string>"):format(fg)) end
    if bgc then table.insert(settings, ("\t\t\t\t<key>background</key>\n\t\t\t\t<string>%s</string>"):format(bgc)) end
    if style then table.insert(settings, ("\t\t\t\t<key>fontStyle</key>\n\t\t\t\t<string>%s</string>"):format(style)) end
    local head = ("\t\t<dict>\n\t\t\t<key>name</key>\n\t\t\t<string>%s</string>\n"):format(name)
    if scope then
      head = head .. ("\t\t\t<key>scope</key>\n\t\t\t<string>%s</string>\n"):format(scope)
    end
    return head .. "\t\t\t<key>settings</key>\n\t\t\t<dict>\n"
      .. table.concat(settings, "\n") .. "\n\t\t\t</dict>\n\t\t</dict>"
  end

  local global = ("\t\t<dict>\n\t\t\t<key>settings</key>\n\t\t\t<dict>\n"
    .. "\t\t\t\t<key>background</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>foreground</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>caret</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>lineHighlight</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>selection</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>gutterForeground</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>invisibles</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t</dict>\n\t\t</dict>"):format(c.bg0, c.fg, c.ember, c.bg1, c.vis, c.gutter, c.bg3)

  local rules = {
    global,
    rule("Comment", "comment, punctuation.definition.comment", c.comment, nil, "italic"),
    rule("String", "string, string.quoted", c.sap),
    rule("String escape", "constant.character.escape", c.ember),
    rule("Regex", "string.regexp", c.ember),
    rule("Number", "constant.numeric", c.sap),
    rule("Boolean and null", "constant.language", c.sap),
    rule("Constant", "constant.other, variable.other.constant", c.fg),
    rule("Keyword", "keyword, storage.type, storage.modifier", c.cinder),
    rule("Operator", "keyword.operator, punctuation.separator, punctuation.terminator", c.fg_dim),
    rule("Punctuation", "punctuation.section, meta.brace", c.fg_dim),
    rule("Function", "entity.name.function, support.function, meta.function-call", c.brass),
    rule("Macro", "entity.name.macro, meta.preprocessor", c.ember),
    rule("Type", "entity.name.type, entity.name.class, support.type, support.class", c.frost),
    rule("Namespace", "entity.name.namespace, entity.name.module", c.frost),
    rule("Variable", "variable, variable.other", c.fg),
    rule("Parameter", "variable.parameter", c.ember),
    rule("Property", "variable.other.member, meta.object-literal.key, support.type.property-name", c.ember),
    rule("Builtin variable", "variable.language", c.cinder),
    rule("Tag", "entity.name.tag", c.cinder),
    rule("Tag attribute", "entity.other.attribute-name", c.ember),
    rule("Decorator", "meta.decorator, punctuation.definition.decorator", c.ember),
    rule("Heading", "markup.heading", c.ember, nil, "bold"),
    rule("Markup bold", "markup.bold", c.brass, nil, "bold"),
    rule("Markup italic", "markup.italic", c.fg, nil, "italic"),
    rule("Markup link", "markup.underline.link", c.frost, nil, "underline"),
    rule("Markup raw", "markup.raw, markup.inline.raw", c.sap),
    rule("Markup quote", "markup.quote", c.comment, nil, "italic"),
    rule("Markup list", "markup.list punctuation.definition", c.ember),
    rule("Diff added", "markup.inserted", c.ok),
    rule("Diff removed", "markup.deleted", c.error),
    rule("Diff changed", "markup.changed", c.info),
    rule("Invalid", "invalid, invalid.illegal", c.error),
    rule("Deprecated", "invalid.deprecated", c.warn),
  }

  return ([[
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>name</key>
	<string>%s</string>
	<key>semanticClass</key>
	<string>theme.dark.%s</string>
	<key>uuid</key>
	<string>%s</string>
	<key>colorSpaceName</key>
	<string>sRGB</string>
	<key>author</key>
	<string>Aejkatappaja</string>
	<key>settings</key>
	<array>
%s
	</array>
</dict>
</plist>
]]):format(palette.name(bg), palette.name(bg),
    ("3f7a1c6e-4b21-4d8f-9c3a-%s"):format(bg == palette.default and "cendre000001"
      or (bg == "medium" and "cendre000002" or "cendre000003")),
    table.concat(rules, "\n"))
end

return M
