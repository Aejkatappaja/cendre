--- bat reads a Sublime Text tmTheme, which is an XML property list. Scopes are
--- grouped the way the Neovim treesitter map groups them.
--- @param bg string
--- @return string
function M.bat(bg)
  local c = palette.get(bg)

  --- @param name string
  --- @param scope string|nil
  --- @param fg string|nil
  --- @param bgc string|nil
  --- @param style string|nil
  --- @return string
  local function rule(name, scope, fg, bgc, style)
    local settings = {}
    if fg then table.insert(settings, ("\t\t\t\t<key>foreground</key>\n\t\t\t\t<string>%s</string>"):format(fg)) end
    if bgc then table.insert(settings, ("\t\t\t\t<key>background</key>\n\t\t\t\t<string>%s</string>"):format(bgc)) end
    if style then table.insert(settings, ("\t\t\t\t<key>fontStyle</key>\n\t\t\t\t<string>%s</string>"):format(style)) end
    local head = ("\t\t<dict>\n\t\t\t<key>name</key>\n\t\t\t<string>%s</string>\n"):format(name)
    if scope then
      head = head .. ("\t\t\t<key>scope</key>\n\t\t\t<string>%s</string>\n"):format(scope)
    end
    return head .. "\t\t\t<key>settings</key>\n\t\t\t<dict>\n"
      .. table.concat(settings, "\n") .. "\n\t\t\t</dict>\n\t\t</dict>"
  end

  local global = ("\t\t<dict>\n\t\t\t<key>settings</key>\n\t\t\t<dict>\n"
    .. "\t\t\t\t<key>background</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>foreground</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>caret</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>lineHighlight</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>selection</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>gutterForeground</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t\t<key>invisibles</key>\n\t\t\t\t<string>%s</string>\n"
    .. "\t\t\t</dict>\n\t\t</dict>"):format(c.bg0, c.fg, c.ember, c.bg1, c.vis, c.gutter, c.bg3)

  local rules = {
    global,
    rule("Comment", "comment, punctuation.definition.comment", c.comment, nil, "italic"),
    rule("String", "string, string.quoted", c.sap),
    rule("String escape", "constant.character.escape", c.ember),
    rule("Regex", "string.regexp", c.ember),
    rule("Number", "constant.numeric", c.sap),
    rule("Boolean and null", "constant.language", c.sap),
