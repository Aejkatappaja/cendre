--- @param hex string
--- @return string "R;G;B" for an SGR truecolor sequence
local function rgb(hex)
  local r, g, b = hex:match("^#(%x%x)(%x%x)(%x%x)$")
  return ("%d;%d;%d"):format(tonumber(r, 16), tonumber(g, 16), tonumber(b, 16))
end

--- @param bg string
--- @return string
function M.fzf(bg)
  local c = palette.get(bg)
  local pairs_ = {
    { "bg+", c.bg1 }, { "bg", c.bg0 }, { "border", c.bg3 },
    { "fg", c.fg_dim }, { "fg+", c.fg }, { "gutter", c.bg0 },
    { "header", c.frost }, { "hl", c.ember }, { "hl+", c.brass },
    { "info", c.comment }, { "marker", c.ok }, { "pointer", c.ember },
    { "prompt", c.cinder }, { "query", c.fg }, { "scrollbar", c.bg3 },
    { "separator", c.bg3 }, { "spinner", c.ember },
  }
  local lines = {}
  for i, kv in ipairs(pairs_) do
    local tail = i == #pairs_ and '"' or " \\"
    table.insert(lines, ("  --color=%s:%s%s"):format(kv[1], kv[2], tail))
  end
  return ([[
# cendre theme for fzf · %s
# %s
%s
#
# Source this file from your shell rc:
#   source /path/to/extras/fzf/cendre.sh

export FZF_DEFAULT_OPTS="$FZF_DEFAULT_OPTS \
%s
]]):format(bg, LINK, GENERATED, table.concat(lines, "\n"))
end

