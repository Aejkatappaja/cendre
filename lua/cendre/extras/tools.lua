]]):format(palette.name(bg), LINK,
    c.bg_deep, c.bg_deep, c.comment, c.bg0, c.fg, c.ember, c.ember,
    c.bg0, c.fg, c.bg1, c.fg, c.bg3, c.bg1, c.vis,
    c.bg3, c.bg3, c.bg3,
    c.bg_deep, c.fg, c.bg3, c.ember, c.bg0,
    c.bg0, c.fg,
    c.bg_deep, c.fg_dim, c.bg3, c.ember, c.bg0,
    c.fg_dim, c.bg1, c.bg2, c.fg_dim, c.ember)
