--- @param hex string
--- @return string "R;G;B" for an SGR truecolor sequence
local function rgb(hex)
  local r, g, b = hex:match("^#(%x%x)(%x%x)(%x%x)$")
  return ("%d;%d;%d"):format(tonumber(r, 16), tonumber(g, 16), tonumber(b, 16))
end

--- @param bg string
--- @return string
function M.fzf(bg)
  local c = palette.get(bg)
  local pairs_ = {
    { "bg+", c.bg1 }, { "bg", c.bg0 }, { "border", c.bg3 },
    { "fg", c.fg_dim }, { "fg+", c.fg }, { "gutter", c.bg0 },
    { "header", c.frost }, { "hl", c.ember }, { "hl+", c.brass },
    { "info", c.comment }, { "marker", c.ok }, { "pointer", c.ember },
    { "prompt", c.cinder }, { "query", c.fg }, { "scrollbar", c.bg3 },
    { "separator", c.bg3 }, { "spinner", c.ember },
  }
  local lines = {}
  for i, kv in ipairs(pairs_) do
    local tail = i == #pairs_ and '"' or " \\"
    table.insert(lines, ("  --color=%s:%s%s"):format(kv[1], kv[2], tail))
  end
  return ([[
# cendre theme for fzf · %s
# %s
%s
#
# Source this file from your shell rc:
#   source /path/to/extras/fzf/cendre.sh

export FZF_DEFAULT_OPTS="$FZF_DEFAULT_OPTS \
%s
]]):format(bg, LINK, GENERATED, table.concat(lines, "\n"))
end

--- @param bg string
--- @return string
function M.eza(bg)
  local c = palette.get(bg)
  -- Filetype and permission keys, each mapped to a pigment by what it means:
  -- directories take the UI accent, anything executable takes the ok green,
  -- anything destructive takes the error red.
  local keys = {
    { "di", c.ember, ";1" }, { "ex", c.ok }, { "fi", c.fg }, { "ln", c.frost },
    { "or", c.error }, { "pi", c.hint }, { "so", c.frost }, { "bd", c.brass },
    { "cd", c.brass }, { "ur", c.brass }, { "uw", c.error }, { "ux", c.ok },
    { "ue", c.ok }, { "gr", c.brass }, { "gw", c.error }, { "gx", c.ok },
    { "tr", c.brass }, { "tw", c.error }, { "tx", c.ok }, { "su", c.cinder },
    { "sf", c.cinder }, { "xa", c.comment }, { "sn", c.fg }, { "sb", c.fg_dim },
    { "uu", c.brass }, { "un", c.fg_dim }, { "gu", c.ember }, { "gn", c.fg_dim },
    { "da", c.comment }, { "in", c.gutter }, { "lc", c.comment }, { "lp", c.frost },
    { "ga", c.ok }, { "gm", c.info }, { "gd", c.error }, { "gv", c.frost },
    { "gt", c.brass }, { "gi", c.gutter }, { "gc", c.warn }, { "hd", c.fg, ";1" },
  }
  local lines = {}
  for i, k in ipairs(keys) do
    local tail = i == #keys and '"' or ":\\"
    table.insert(lines, ("%s=38;2;%s%s%s"):format(k[1], rgb(k[2]), k[3] or "", tail))
  end
  return ([[
# cendre theme for eza (https://eza.rocks) · %s
# %s
%s
#
# Install: source this file from your shell rc.
#   source /path/to/extras/eza/cendre.sh

export EZA_COLORS="\
%s
]]):format(bg, LINK, GENERATED, table.concat(lines, "\n"))
end

